#!/bin/bash
# build.sh <graalvm-home> <out-dir>
#
# Builds Substrate VM's C libraries for Windows on ARM64 (GraalVM CE ships them for windows-amd64 only): libchelper.lib
# and jvm.lib, from oracle/graal at the release's commit, with patches/*.patch applied to them. Run in an ARM64 MSVC
# environment (vcvarsall arm64).
set -euo pipefail
export MSYS2_ARG_CONV_EXCL='*'
graal=$(cd "$1" && pwd); out=$2
recipe=$(cd "$(dirname "$0")/.." && pwd)
mkdir -p "$out"; out=$(cd "$out" && pwd)
work=$(mktemp -d)
"$recipe/scripts/graal-sources.sh" "$graal" "$work" substratevm/src/com.oracle.svm.native.libchelper/ substratevm/src/com.oracle.svm.native.jvm.windows/

src=$work/substratevm/src
w() { cygpath -w "$1"; }
compile() { # <lib> <cflags> <dir>...
  local lib=$1 flags=$2; shift 2
  local objs="$work/obj/$lib"; mkdir -p "$objs"
  for dir in "$@"; do
    for c in "$dir"/*.c; do
      # shellcheck disable=SC2086
      cl -nologo -c $flags -I"$(w "$src/com.oracle.svm.native.libchelper/include")" -I"$(w "$graal/include")" -I"$(w "$graal/include/win32")" \
        -Fo"$(w "$objs/$(basename "$c" .c).obj")" "$(w "$c")"
    done
  done
  lib -nologo -machine:arm64 -out:"$(w "$out/$lib.lib")" "$(w "$objs")"/*.obj
  echo "$out/$lib.lib"; lib -nologo -list "$(w "$out/$lib.lib")"
}
compile libchelper "-MD -Zi -O2 -D_LITTLE_ENDIAN" "$src/com.oracle.svm.native.libchelper/src"
# jvm.lib's fallbacks (generated by mx, not in the sources): a stub per function of GraalVM CE's windows-amd64 one, which
# fails if ever called
fallbacks=$work/fallbacks; mkdir -p "$fallbacks"
amd64jvm=$(w "$graal/lib/svm/clibraries/windows-amd64/jvm.lib")
member=$(lib -nologo -list "$amd64jvm" | tr -d '\r' | grep -i 'JvmFuncsFallbacks.obj')
(cd "$fallbacks" && lib -nologo -extract:"$member" -out:amd64.obj "$amd64jvm")
{
  echo '/* Generated: the JVM functions Substrate VM does not implement, from the windows-amd64 jvm.lib (JvmFuncsFallbacks.obj) */'
  echo '#include <stdio.h>'
  echo '#include <stdlib.h>'
  echo 'static void unimplemented(const char *name) { fprintf(stderr, "%s is not supported in a native image\n", name); abort(); }'
  dumpbin -nologo -symbols "$(w "$fallbacks/amd64.obj")" | tr -d '\r' | grep -E 'SECT[0-9A-F]+ .*External' | sed 's/.*| //' | grep -v '^\.' | sort -u |
    while read -r name; do echo "void $name(void) { unimplemented(\"$name\"); }"; done
} > "$fallbacks/JvmFuncsFallbacks.c"
grep -c '^void' "$fallbacks/JvmFuncsFallbacks.c"
compile jvm "-MD -Zi -O2 -DJNIEXPORT=" "$src/com.oracle.svm.native.jvm.windows/src" "$fallbacks"
